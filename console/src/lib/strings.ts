export type Strings = typeof strings;

export function problemText(slug: ProblemSlug): string {
  return problems[slug] ?? problems.unknown;
}

export function tlsStepText(key: string, params: Record<string, string>): string {
  const template = tlsSteps[key];
  if (template) return fmt(template, params);
  const tail = key.split(".").slice(3).join(" ").replace(/-/g, " ");
  const extra = Object.values(params).join(", ");
  return `${tail.charAt(0).toUpperCase()}${tail.slice(1)}.${extra ? ` (${extra})` : ""}`;
}

// The operator text of a job kind. An unknown kind shows as it is.
export function jobKindText(kind: string | null | undefined): string {
  if (!kind) return "";
  return strings.jobs.kinds[kind] ?? kind;
}

// The operator text of a step action key (docs/console-ui.md section 9), or the key itself.
export function stepActionText(action: string | null | undefined): string {
  if (!action) return "";
  return strings.steps.actions[action] ?? action;
}
