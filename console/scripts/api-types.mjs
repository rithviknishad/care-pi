#!/usr/bin/env node
// Make src/api/types.gen.ts from docs/api/openapi.yaml (docs/api/README.md section 9.2).
// 1. Redocly bundles the contract into one JSON file. The bundle puts the parts of
//    config.schema.json in components, so the config types get names.
// 2. openapi-typescript makes the TypeScript types from the bundle.
// The bundle is a build file in node_modules/.cache. Commit only types.gen.ts.
// --check writes nothing in src/. It exits with code 1 when types.gen.ts is not the same as a new file.

import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = path.resolve(ROOT, "../docs/api/openapi.yaml");
const CACHE = path.join(ROOT, "node_modules/.cache/care-pi-console");
const BUNDLE = path.join(CACHE, "openapi.bundled.json");
const TYPES = path.join(ROOT, "src/api/types.gen.ts");
const check = process.argv.includes("--check");
const OUT = check ? path.join(CACHE, "types.gen.ts") : TYPES;

const env = { ...process.env, REDOCLY_TELEMETRY: "off", REDOCLY_SUPPRESS_UPDATE_NOTICE: "true" };

function run(bin, args) {
  const result = spawnSync(path.join(ROOT, "node_modules/.bin", bin), args, { cwd: ROOT, env, stdio: "inherit" });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

mkdirSync(CACHE, { recursive: true });
run("redocly", ["bundle", SPEC, "--ext", "json", "-o", BUNDLE]);
run("openapi-typescript", [BUNDLE, "-o", OUT]);

const version = JSON.parse(readFileSync(BUNDLE, "utf8")).info.version;
const header =
  "// Generated by `npm run api:types` from docs/api/openapi.yaml (contract version " +
  version +
  ").\n// Do not edit this file.\n\n";
writeFileSync(OUT, header + readFileSync(OUT, "utf8").replace(/^\/\*\*[\s\S]*?\*\/\n\n/, ""));
if (check) {
  if (readFileSync(OUT, "utf8") !== readFileSync(TYPES, "utf8")) {
    console.error(`${path.relative(ROOT, TYPES)} is not the same as the contract ${version}. Run npm run api:types.`);
    process.exit(1);
  }
  console.log(`${path.relative(ROOT, TYPES)} is the same as the contract ${version}.`);
} else {
  console.log(`wrote ${path.relative(ROOT, OUT)} (contract ${version})`);
}
