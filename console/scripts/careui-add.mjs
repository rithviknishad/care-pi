#!/usr/bin/env node
// Add Care UI (careui) components to the console from the careui registry.
//
//   node scripts/careui-add.mjs button card dialog
//   node scripts/careui-add.mjs --overwrite button
//   node scripts/careui-add.mjs --registry ~/ohc.network/careui/public button
//   node scripts/careui-add.mjs --tokens ~/ohc.network/careui/src/index.css
//   node scripts/careui-add.mjs --check
//
// The script downloads https://careui.ohc.network/registry/care-ui/<name>/<name>.json,
// follows registryDependencies, and writes files[].content into src/components/ui/
// (src/hooks/ for use-* items). It records each item in src/components/ui/careui-lock.json.
// It does not install npm packages. It prints the npm install command for the dependencies.
// The shadcn CLI is not necessary: it cannot resolve ui.shadcn.com on some machines.
//
// --tokens copies the careui design tokens (src/index.css of the careui repository)
// into src/styles/careui.css. It removes the @import lines and the docs-only rules.
//
// --check makes no request. It compares each file in careui-lock.json with its sha256.
// A difference is a local edit of a registry file: the script exits with code 1.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_REGISTRY = "https://careui.ohc.network";
const UI_DIR = path.join(ROOT, "src/components/ui");
const HOOKS_DIR = path.join(ROOT, "src/hooks");
const LOCK = path.join(UI_DIR, "careui-lock.json");
const TOKENS_OUT = path.join(ROOT, "src/styles/careui.css");

function usage(code) {
  console.log(
    "usage: careui-add.mjs [--overwrite] [--registry URL|DIR] <name>...\n" +
      "       careui-add.mjs --tokens <careui src/index.css path or URL>\n" +
      "       careui-add.mjs --check",
  );
  process.exit(code);
}

const args = process.argv.slice(2);
let overwrite = false;
let registry = DEFAULT_REGISTRY;
let tokens = null;
let check = false;
const names = [];
for (let i = 0; i < args.length; i++) {
  const a = args[i];
  if (a === "--overwrite") overwrite = true;
  else if (a === "--registry") registry = args[++i] ?? usage(2);
  else if (a === "--tokens") tokens = args[++i] ?? usage(2);
  else if (a === "--check") check = true;
  else if (a === "-h" || a === "--help") usage(0);
  else if (a.startsWith("-")) usage(2);
  else names.push(a);
}
if (!check && !tokens && names.length === 0) usage(2);

function expandHome(p) {
  return p.startsWith("~/") ? path.join(process.env.HOME ?? "", p.slice(2)) : p;
}

async function readSource(location) {
  if (/^https?:\/\//.test(location)) {
    const res = await fetch(location);
    if (!res.ok) throw new Error(`GET ${location}: ${res.status}`);
    return res.text();
  }
  return readFileSync(expandHome(location), "utf8");
}

// A registryDependency is a name or an absolute URL of the public registry.
// With --registry DIR, the script reads the same item from the local checkout.
function itemLocation(nameOrUrl) {
  const name = /^https?:\/\//.test(nameOrUrl) ? path.basename(new URL(nameOrUrl).pathname, ".json") : nameOrUrl;
  const base = registry.replace(/\/$/, "");
  const sub = `registry/care-ui/${name}/${name}.json`;
  return { name, location: /^https?:\/\//.test(base) ? `${base}/${sub}` : path.join(expandHome(base), sub) };
}

function targetPath(item, file) {
  const base = path.basename(file.path);
  if (item.type === "registry:hook" || base.startsWith("use-")) return path.join(HOOKS_DIR, base);
  return path.join(UI_DIR, base);
}

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

async function copyTokens(location) {
  const css = await readSource(location);
  const body = css
    .split("\n")
    .filter((line) => !/^@import\s/.test(line))
    .join("\n")
    // The docs site uses .typeset-docs with Figtree. The console does not.
    .replace(/\n\.typeset-docs\s*\{[^}]*\}\n?/g, "\n")
    .trim();
  const header =
    "/*\n" +
    " * Care UI design tokens. Do not edit this file.\n" +
    ` * Source: ${location.startsWith(process.env.HOME ?? "\0") ? location.replace(process.env.HOME, "~") : location}\n` +
    ` * sha256 of the source: ${sha256(css)}\n` +
    " * Update: npm run careui:add -- --tokens <careui>/src/index.css\n" +
    " * src/index.css has the @import lines of the source.\n" +
    " */\n\n";
  mkdirSync(path.dirname(TOKENS_OUT), { recursive: true });
  writeFileSync(TOKENS_OUT, header + body + "\n");
  console.log(`wrote ${path.relative(ROOT, TOKENS_OUT)}`);
}

async function addItems(requested) {
  const lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, "utf8")) : { registry: DEFAULT_REGISTRY, items: {} };
  const seen = new Set();
  const deps = new Set();
  const queue = requested.map(itemLocation);
  while (queue.length > 0) {
    const { name, location } = queue.shift();
    if (seen.has(name)) continue;
    seen.add(name);
    const item = JSON.parse(await readSource(location));
    for (const d of item.dependencies ?? []) deps.add(d);
    for (const r of item.registryDependencies ?? []) queue.push(itemLocation(r));
    const files = [];
    for (const file of item.files ?? []) {
      if (typeof file.content !== "string") throw new Error(`${name}: ${file.path} has no content`);
      const out = targetPath(item, file);
      mkdirSync(path.dirname(out), { recursive: true });
      const rel = path.relative(ROOT, out);
      if (existsSync(out) && !overwrite) {
        console.log(`keep  ${rel} (exists; use --overwrite)`);
      } else {
        writeFileSync(out, file.content.endsWith("\n") ? file.content : file.content + "\n");
        console.log(`write ${rel}`);
      }
      files.push({ path: rel, sha256: sha256(file.content) });
    }
    lock.items[name] = {
      source: `${DEFAULT_REGISTRY}/registry/care-ui/${name}/${name}.json`,
      dependencies: item.dependencies ?? [],
      files,
    };
  }
  lock.items = Object.fromEntries(Object.entries(lock.items).sort(([a], [b]) => a.localeCompare(b)));
  mkdirSync(UI_DIR, { recursive: true });
  writeFileSync(LOCK, JSON.stringify(lock, null, 2) + "\n");

  const pkg = JSON.parse(readFileSync(path.join(ROOT, "package.json"), "utf8"));
  const have = { ...pkg.dependencies, ...pkg.devDependencies };
  const all = [...deps].sort();
  const missing = all.filter((d) => !(d in have));
  console.log(`\nnpm dependencies of these items: ${all.join(" ") || "(none)"}`);
  if (missing.length > 0) console.log(`install: npm install ${missing.join(" ")}`);
  else console.log("package.json has each npm dependency.");
}

// The script writes content + "\n" when the registry content has no final newline.
function checkLock() {
  const lock = JSON.parse(readFileSync(LOCK, "utf8"));
  let bad = 0;
  let count = 0;
  for (const [name, item] of Object.entries(lock.items)) {
    for (const file of item.files) {
      count++;
      const abs = path.join(ROOT, file.path);
      const text = existsSync(abs) ? readFileSync(abs, "utf8") : null;
      const ok = text !== null && (sha256(text) === file.sha256 || sha256(text.replace(/\n$/, "")) === file.sha256);
      if (!ok) {
        bad++;
        console.log(`${text === null ? "missing " : "changed "} ${file.path} (${name})`);
      }
    }
  }
  console.log(
    `${count - bad} of ${count} files are the same as the registry (${Object.keys(lock.items).length} items).`,
  );
  if (bad > 0) process.exit(1);
}

if (check) checkLock();
if (tokens) await copyTokens(tokens);
if (names.length > 0) await addItems(names);
