func TestRegistry(t *testing.T) {
	p, err := New("none", Env{})
	if err != nil || p.Name() != "none" {
		t.Fatalf("none: %v", err)
	}
	if b, err := p.Ensure(context.Background(), "x"); b.Dir != "" || err != nil {
		t.Fatal("none must return no build")
	}
	for _, name := range []string{"artifact", "local"} {
		p, err := New(name, Env{})
		if err != nil || p.Name() != name {
			t.Fatalf("%s: %v", name, err)
		}
	}
	if _, err := New("remote-build", Env{}); !errors.Is(err, ErrNotImplemented) {
		t.Fatalf("remote-build: %v", err)
	}
}

func TestBuildIDIsStable(t *testing.T) {
	a := BuildID("abc", map[string]string{"X": "1", "Y": "2"})
	b := BuildID("abc", map[string]string{"Y": "2", "X": "1"})
	c := BuildID("abc", map[string]string{"X": "1", "Y": "3"})
	if a != b || a == c || len(a) != 16 {
		t.Fatalf("a=%s b=%s c=%s", a, b, c)
	}
	// A fixed vector: the agent and the fe-bundle workflow must keep the same ids.
	if got := BuildID(strings.Repeat("a", 40), map[string]string{"REACT_CARE_API_URL": ""}); got != "b5e55d6293a872fb" {
		t.Fatalf("the build id function changed: %s", got)
	}
}

func TestParseEnvFile(t *testing.T) {
	in := "# Generated by care-pi\n\nREACT_CARE_API_URL=\nREACT_X=a=b c \"d\"\n"
	got, err := ParseEnvFile(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]string{"REACT_CARE_API_URL": "", "REACT_X": "a=b c \"d\""}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %q", got)
	}
	for _, bad := range []string{"NOEQUALS\n", "1X=2\n", "A B=1\n"} {
		if _, err := ParseEnvFile(strings.NewReader(bad)); err == nil {
			t.Errorf("want an error for %q", bad)
		}
	}
}

func TestSetCurrent(t *testing.T) {
	p := paths.New(t.TempDir())
	for _, id := range []string{"build1", "build2"} {
		writeBuild(t, p, id)
	}
	if err := SetCurrent(p, "build1"); err != nil {
		t.Fatal(err)
	}
	if err := SetCurrent(p, "build2"); err != nil {
		t.Fatal(err)
	}
	if Current(p) != "build2" {
		t.Fatalf("current = %s", Current(p))
	}
	target, _ := os.Readlink(p.Abs(paths.FECurrent))
	if target != "build2" {
		t.Fatalf("the link must be relative, got %s", target)
	}
	if err := SetCurrent(p, "missing"); err == nil {
		t.Fatal("want an error for a build without index.html")
	}
	if err := SetCurrent(p, "../x"); err == nil {
		t.Fatal("want an error for a bad id")
	}
}

