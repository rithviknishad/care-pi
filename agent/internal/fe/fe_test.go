func TestListAndPrune(t *testing.T) {
	p := paths.New(t.TempDir())
	ids := []string{"b1", "b2", "b3", "b4"}
	base := time.Date(2026, 10, 30, 10, 0, 0, 0, time.UTC)
	for i, id := range ids {
		dir := writeBuild(t, p, id)
		mt := base.Add(-time.Duration(i) * time.Hour)
		if err := os.Chtimes(dir, mt, mt); err != nil {
			t.Fatal(err)
		}
	}
	if err := SetCurrent(p, "b4"); err != nil {
		t.Fatal(err)
	}
	_ = os.MkdirAll(p.Abs(paths.FEDir+"/.tmp-b5-123"), 0o755)
	_ = os.MkdirAll(p.Abs(paths.FEDir+"/b6.tmp"), 0o755)
	list, err := List(p)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, b := range list {
		got = append(got, b.ID)
		if b.Bytes == 0 {
			t.Errorf("%s: no size", b.ID)
		}
	}
	if strings.Join(got, " ") != "b1 b2 b3 b4" || !list[3].Current {
		t.Fatalf("list: %v", got)
	}
	if _, err := Prune(context.Background(), p, 0); err == nil {
		t.Fatal("want an error for keep 0")
	}
	removed, err := Prune(context.Background(), p, 2)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(removed, " ") != "b3 .tmp-b5-123 b6.tmp" {
		t.Fatalf("removed %v", removed)
	}
	for _, id := range []string{"b1", "b2", "b4"} {
		if !Exists(p, id) {
			t.Errorf("%s was removed", id)
		}
	}
}

func writeBuild(t *testing.T, p paths.Paths, id string) string {
	t.Helper()
	dir := p.Abs(Dir(id))
	if err := os.MkdirAll(filepath.Join(dir, "assets"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "index.html"), []byte("<html>"+id), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}
