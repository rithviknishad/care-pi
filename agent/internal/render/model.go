// GitHubSlug returns OWNER/NAME for a https://github.com/OWNER/NAME URL, else "".
func GitHubSlug(repo string) string {
	rest, ok := strings.CutPrefix(repo, "https://github.com/")
	if !ok {
		return ""
	}
	rest = strings.TrimSuffix(strings.TrimSuffix(rest, "/"), ".git")
	parts := strings.Split(rest, "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return ""
	}
	return rest
}

func checkBuckets(b Buckets) error {
	for _, name := range []string{b.Patient, b.Facility} {
		if !bucketRE.MatchString(name) {
			return fmt.Errorf("render: bucket name %q is not valid (3 to 63 characters: a-z, 0-9, dot, dash)", name)
		}
		if reservedPaths[name] {
			return fmt.Errorf("render: bucket name %q collides with a Caddy route; choose a different name", name)
		}
	}
	if b.Patient == b.Facility {
		return fmt.Errorf("render: FILE_UPLOAD_BUCKET and FACILITY_S3_BUCKET must differ")
	}
	if !regionRE.MatchString(b.Region) {
		return fmt.Errorf("render: BUCKET_REGION %q is not valid", b.Region)
	}
	return nil
}

