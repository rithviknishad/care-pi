// connectivity fills the Phase 6 part of the model (docs/connectivity.md).
func connectivity(m *Model, cfg *config.Config, in Input) error {
	m.LocalHosts = LocalHostnames(cfg)
	m.LocalSites = append(append([]string{}, m.LocalHosts...), m.IPs...)
	if len(m.LocalSites) == 0 {
		return fmt.Errorf("render: the local CA mode has no name and no LAN address to serve")
	}
	m.HSTS = HSTSValue
	m.FirewallUnit = paths.FirewallUnit
	m.Firewall = FirewallOf(cfg)
	m.FirewallFile = paths.FirewallFile
	m.FirewallDropInFile = paths.FirewallDropIn
	m.FirewallDropConfirmed = in.FirewallDropConfirmed
	m.WaitAddressTimeout = "30s"
	m.TailscaleSocketDir = paths.TailscaleSocketDir
	if in.CARoot {
		m.CARoot = true
		m.CACert = paths.CACaddyDir + "/" + ca.CertFile
		m.CAKey = paths.CACaddyDir + "/" + ca.KeyFile
	}
	m.PublicHost = PublicHost(cfg)
	if m.PublicHost != "" {
		if !in.ACMEDNS {
			return fmt.Errorf("render: tls.public is on, but this device has no registration with the DNS service (%s); run: care-pi tls public enable", paths.ACMEDNSFile)
		}
		m.PublicACMECA = cfg.TLS.Public.ACMECA
		m.PublicIssued = in.PublicIssued
		m.ACMEDNSSecret = ACMEDNSSecret
		m.ACMEDNSFile = "/run/secrets/" + ACMEDNSSecret
		m.DNSUpdate = !in.Bootstrap
	}
	m.TailscaleHost = TailscaleHost(cfg)
	if m.TailscaleHost != "" {
		m.TailscaleIP = in.TailscaleIP
		m.FirewallTailscale = true
	}
	// Port 80 (07 §6.1): when the public name has its certificate, the local names and the public name send
	// the browser to the public name. The LAN addresses keep their own redirect, so an IP still works offline.
	if m.PublicHost != "" && m.PublicIssued {
		m.Port80Public = append(append([]string{}, m.LocalHosts...), m.PublicHost)
		m.Port80Same = append([]string{}, m.IPs...)
	} else {
		m.Port80Same = append(append([]string{}, m.LocalSites...), nonEmpty(m.PublicHost)...)
	}
	m.Port80Same = append(m.Port80Same, nonEmpty(m.TailscaleHost)...)
	return nil
}

func nonEmpty(s string) []string {
	if s == "" {
		return nil
	}
	return []string{s}
}

func customFrontendRefs(cfg *config.Config) bool {
	for _, c := range cfg.Solution.Custom.Plugs {
		if c.Frontend != nil && c.Frontend.Ref != "" {
			return true
		}
	}
	return false
}

// SecretMask replaces a secret value in rendered/care/additional-plugs.json.
const SecretMask = "<secret>"

// PlugConfigs returns the configs of the ADDITIONAL_PLUGS entry of a plug (docs/solutions.md, section 1.4):
// backend.configs, then the default of each backend setting, then the operator values of
// solution.plugs.<id>.settings.backend, then the secrets. red has each secret value replaced by SecretMask.
func PlugConfigs(cfg *config.Config, p solution.Plug, secretValues map[string]any) (full, red map[string]any) {
	full = map[string]any{}
	if p.Backend != nil {
		for k, v := range p.Backend.Configs {
			full[k] = solution.DeepCopy(v)
		}
	}
	var op map[string]any
	if ch, ok := cfg.Solution.Plugs[p.ID]; ok && ch.Settings != nil {
		op = ch.Settings.Backend
	}
	secretKeys := map[string]bool{}
	for _, st := range p.TypedSettings() {
		if st.Part != solution.PartBackend {
			continue
		}
		if st.Type == solution.TypeSecret {
			secretKeys[st.Key] = true
			if v, ok := secretValues[st.Key]; ok && v != nil {
				full[st.Key] = v
			}
			continue
		}
		if st.Default != nil {
			full[st.Key] = solution.DeepCopy(st.Default)
		}
		if v, ok := op[st.Key]; ok && v != nil {
			full[st.Key] = solution.DeepCopy(v)
		}
	}
	red = map[string]any{}
	for k, v := range full {
		red[k] = v
		if secretKeys[k] {
			if _, set := secretValues[k]; set {
				red[k] = SecretMask
			}
		}
	}
	return full, red
}

