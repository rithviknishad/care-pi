// Hostnames returns the DNS names that the config serves, the canonical name first (docs/connectivity.md):
// the public name when tls.public is on (S36: primary when online), then the local CA name, then the
// Tailscale name. More than one name turns on the plugs with auto: when_multihost (P10). IP addresses do not count.
func Hostnames(cfg *config.Config) []string {
	var out []string
	if h := PublicHost(cfg); h != "" {
		out = append(out, h)
	}
	out = append(out, LocalHostnames(cfg)...)
	if h := TailscaleHost(cfg); h != "" {
		out = append(out, h)
	}
	return out
}

// LocalHostnames returns the names of the local CA mode: <hostname>.local.
func LocalHostnames(cfg *config.Config) []string {
	if !cfg.TLS.LocalCA.Enabled {
		return nil
	}
	return []string{netinfo.MDNSName(cfg.Identity.Hostname)}
}

// PublicHost returns <clinic_id>.care-pi.rithviknishad.dev when tls.public is on, else "".
func PublicHost(cfg *config.Config) string {
	if !cfg.TLS.Public.Enabled || cfg.TLS.Public.ClinicID == "" {
		return ""
	}
	return cfg.TLS.Public.ClinicID + "." + ca.PublicZone
}

// TailscaleHost returns the MagicDNS name when tls.tailscale is on, else "".
func TailscaleHost(cfg *config.Config) string {
	if !cfg.TLS.Tailscale.Enabled {
		return ""
	}
	return cfg.TLS.Tailscale.Hostname
}

// Plan holds what the config and the solution ask for, before the lock resolves it.
type Plan struct {
	Plugs    []solution.EffectivePlug
	Wants    lock.Wants
	Backend  map[string]string
	Frontend map[string]string
}

// careRef returns the ref of the care image.
func careRef(cfg *config.Config, sol *solution.Solution) string {
	if cfg.Solution.Track == "custom" && cfg.Solution.Custom.CareRef != "" {
		return cfg.Solution.Custom.CareRef
	}
	if sol.Care.Ref != "" {
		return sol.Care.Ref
	}
	return "latest"
}

func joinImage(repo, ref string) string {
	if len(ref) > 7 && ref[:7] == "sha256:" {
		return repo + "@" + ref
	}
	return repo + ":" + ref
}

// Desire computes the plugs, the refs to resolve, and the merged env.
func Desire(cfg *config.Config, sol *solution.Solution) (*Plan, error) {
	return DesireLock(cfg, sol, nil, nil)
}

// DesireLock is Desire for a solution lock (sl) and a local care build (cb). sol must be the solution
// of the lock. The refs come from the lock; config.images and solution.custom override them.
func DesireLock(cfg *config.Config, sol *solution.Solution, sl *solution.Lock, cb *CareBuild) (*Plan, error) {
	hosts := Hostnames(cfg)
	plugs, err := sol.Effective(cfg, len(hosts))
	if err != nil {
		return nil, err
	}
	w := lock.Wants{
		Solution: lock.Solution{Name: cfg.Solution.Name, Track: cfg.Solution.Track},
		Images:   map[string]string{},
		Git:      map[string]lock.GitWant{},
		Plugs:    map[string]lock.GitWant{},
	}
	if sl != nil {
		w.Solution.Version, w.Solution.Source, w.Solution.LockSHA256 = sl.Version, lock.SourceLock, sl.SHA256
	}
	backendPlugs := 0
	for _, p := range plugs {
		if p.On && p.HasBackend() {
			backendPlugs++
			w.Plugs[p.ID] = lock.GitWant{Repo: trimGitPlus(p.Backend.Package), Ref: p.Backend.Ref}
		}
	}
	lockRef := func(name, def string) string {
		if sl != nil {
			if img, ok := sl.Images[name]; ok && img.Ref != "" {
				return img.Ref
			}
		}
		return def
	}
	care := cfg.Images.Care
	switch {
	case care != "":
	case cb != nil:
		care = cb.Image()
	case sl != nil:
		care = sl.SolutionImage.Ref()
	case backendPlugs == 0:
		care = joinImage(firstNonEmpty(sol.Care.Image, ImageCareUpstream), careRef(cfg, sol))
	default:
		care = ImageCareSolution + ":" + cfg.Solution.Name + "-latest"
	}
	w.Images["care"] = care
	w.Images["postgres"] = firstNonEmpty(cfg.Images.Postgres, lockRef("postgres", ImagePostgres))
	w.Images["caddy"] = firstNonEmpty(cfg.Images.Caddy, lockRef("caddy", ImageCaddy))
	w.Images["redis"] = firstNonEmpty(cfg.Images.Redis, lockRef("redis", ImageRedis))
	w.Images["s3"] = firstNonEmpty(cfg.Images.S3, lockRef("s3", ImageS3))
	if cfg.FE.Provider != "none" {
		repo, ref := sol.CareFE.Repo, sol.CareFE.Ref
		if sl != nil {
			repo, ref = sl.CareFE.Repo, sl.CareFE.Ref
		}
		if cfg.Solution.Track == "custom" && cfg.Solution.Custom.CareFERef != "" {
			ref = cfg.Solution.Custom.CareFERef
		}
		w.Git["care_fe"] = lock.GitWant{Repo: repo, Ref: ref}
	}
	if cfg.FE.Provider == "local" {
		w.Images["node"] = firstNonEmpty(cfg.Images.Node, lockRef("node", ImageNode))
	}
	// Phase 7: the images of the opt-in telemetry, only when it is on (docs/telemetry.md).
	if cfg.Telemetry.Enabled {
		w.Images["vmagent"] = lockRef("vmagent", ImageVMAgent)
		w.Images["node-exporter"] = lockRef("node-exporter", ImageNodeExporter)
	}
	plugEnv := solution.PlugEnv(plugs)
	backend := solution.MergeEnv(nil, backendDefaults(cfg), sol.Env.Backend, plugEnv.Backend, cfg.Env.Backend)
	frontend := solution.MergeEnv(solution.MultiValueFrontendKeys, sol.Env.Frontend, plugEnv.Frontend, cfg.Env.Frontend)
	for _, k := range config.ReservedBackendEnv {
		delete(backend, k)
	}
	for _, k := range config.ReservedFrontendEnv {
		delete(frontend, k)
	}
	// REACT_PUBLIC_URL only sets the og:url meta tag, and the .env file of care_fe has a
	// default. care-pi does not set it, so the build id does not depend on the host name
	// and the default bundle of the fe-bundle workflow matches (docs/fe.md).
	frontend["REACT_CARE_API_URL"] = ""
	return &Plan{Plugs: plugs, Wants: w, Backend: backend, Frontend: frontend}, nil
}

// backendDefaults are the variables that care-pi sets and the solution or the operator can change.
func backendDefaults(cfg *config.Config) map[string]string {
	d := map[string]string{
		"BUCKET_REGION":                         "ap-south-1",
		"DJANGO_SECURE_HSTS_INCLUDE_SUBDOMAINS": "False",
		"DJANGO_SECURE_HSTS_PRELOAD":            "False",
		"DJANGO_SECURE_SSL_REDIRECT":            "False",
		"DJANGO_SETTINGS_MODULE":                "config.settings.production",
		"FACILITY_S3_BUCKET":                    "facility-bucket",
		"FILE_UPLOAD_BUCKET":                    "patient-bucket",
		"USE_SMS":                               "False",
	}
	// Care builds password reset links from CURRENT_DOMAIN.
	if hosts := Hostnames(cfg); len(hosts) > 0 {
		d["CURRENT_DOMAIN"] = "https://" + hosts[0]
	}
	return d
}

func trimGitPlus(pkg string) string {
	if len(pkg) > 4 && pkg[:4] == "git+" {
		return pkg[4:]
	}
	return pkg
}

func firstNonEmpty(vs ...string) string {
	for _, v := range vs {
		if v != "" {
			return v
		}
	}
	return ""
}

// NewModel builds the template data.
func NewModel(in Input) (*Model, error) {
	cfg := in.Config
	if cfg == nil || in.Solution == nil || in.Lock == nil {
		return nil, fmt.Errorf("render: config, solution, and lock are required")
	}
	pl, err := DesireLock(cfg, in.Solution, in.SolutionLock, in.CareBuild)
	if err != nil {
		return nil, err
	}
	hosts := Hostnames(cfg)
	m := &Model{
		SolutionName:     cfg.Solution.Name,
		CareBuild:        in.CareBuild,
		MaintenanceSteps: MaintenanceSteps,
		Header:           Header,
		DisplayName:      cfg.Identity.DisplayName,
		Hostnames:        hosts,
		IPs:              append([]string(nil), in.IPs...),
		Sizing:           cfg.Sizing(),
		Images:           map[string]string{},
		UploadMaxMB:      cfg.Uploads.MaxBodyMB,
		FEProvider:       cfg.FE.Provider,
		Stanza:           StanzaName,
		Secrets: SecretNames{
			DjangoSecretKey:  secrets.PodmanDjangoSecretKey,
			JWKSBase64:       secrets.PodmanJWKSBase64,
			PostgresPassword: secrets.PodmanPostgresPassword,
			DatabaseURL:      secrets.PodmanDatabaseURL,
			S3AccessKey:      secrets.PodmanS3AccessKey,
			S3SecretKey:      secrets.PodmanS3SecretKey,
			PGBackRestCipher: secrets.PodmanPGBackRestCipher,
		},
		DB:              DBSettings{User: secrets.DBUser, Name: secrets.DBName, Host: secrets.DBHost, Port: secrets.DBPort},
		Units:           Units,
		FEMemoryHigh:    config.FEBuildMemoryHigh,
		FEMemoryMax:     config.FEBuildMemoryMax,
		FEMemorySwap:    config.FEBuildMemorySwap,
		ModeClockWait:   paths.ModeClockWait,
		ModeMaintenance: paths.ModeMaintenance,
		Bootstrap:       in.Bootstrap,
		ConsolePort:     paths.ConsolePort,
		AgentSocket:     paths.AgentSocket,
		AgentUnit:       paths.AgentUnit,
	}
	if in.Bootstrap {
		m.Units = BootstrapUnits
	}
	if len(hosts) > 0 {
		m.Canonical = hosts[0]
	} else if len(m.IPs) > 0 {
		m.Canonical = m.IPs[0]
	}
	if len(m.IPs) > 0 {
		m.PrimaryIP = m.IPs[0]
	}
	m.Sites = append(append([]string{}, hosts...), m.IPs...)
	if len(m.Sites) == 0 {
		return nil, fmt.Errorf("render: no hostname and no LAN address to serve; connect the host to a network")
	}
	if err := connectivity(m, cfg, in); err != nil {
		return nil, err
	}
	if t := cfg.Telemetry; t.Enabled && !in.Bootstrap {
		interval := t.IntervalS
		if interval <= 0 {
			interval = config.DefaultTelemetryIntervalS
		}
		m.Telemetry = TelemetryModel{Enabled: true, RemoteWriteURL: t.RemoteWriteURL, Username: t.Username,
			Interval: fmt.Sprintf("%ds", interval), Instance: cfg.Identity.Hostname, Version: buildinfo.Version,
			ExporterPort: 9100, AgentPort: 8429, RenderedDir: paths.RenderedTelemetry, TextfileDir: paths.TelemetryTextfileDir,
			QueueDir: paths.TelemetryQueueDir}
		if in.TelemetryPassword {
			m.Telemetry.PasswordSecret = TelemetrySecret
		}
	}

	s := m.Sizing
	m.MemAPI = config.MemAPI(s.GunicornWorkers)
	m.MemWork = config.MemWorker(s.CeleryConcurrency)
	m.MemBeat = config.MemBeat
	m.MemDB = config.MemDB(s.PGSharedBuffersMB)
	m.MemRed = config.MemRedis
	m.MemS3 = config.MemS3
	m.MemCad = config.MemCaddy
	if w := cfg.Security.WAF; w.Enabled {
		m.WAF = WAFModel{Enabled: true, Engine: "DetectionOnly", Paranoia: w.Paranoia}
		if w.Mode == "block" {
			m.WAF.Engine = "On"
		}
		if m.WAF.Paranoia < 1 {
			m.WAF.Paranoia = 1
		}
		m.MemCad = config.MemCaddyWAF
	}

	for name := range pl.Wants.Images {
		if in.Bootstrap && name != "caddy" {
			continue
		}
		img, ok := in.Lock.Images[name]
		if !ok || img.Ref != pl.Wants.Images[name] {
			return nil, fmt.Errorf("render: the lock has no entry for image %s (%s)", name, pl.Wants.Images[name])
		}
		m.Images[name] = img.Pull()
	}

	m.Buckets = Buckets{
		Patient:  pl.Backend["FILE_UPLOAD_BUCKET"],
		Facility: pl.Backend["FACILITY_S3_BUCKET"],
		Region:   pl.Backend["BUCKET_REGION"],
	}
	if err := checkBuckets(m.Buckets); err != nil {
		return nil, err
	}

	var redacted []AdditionalPlug
	for _, p := range pl.Plugs {
		if !p.On || !p.HasBackend() {
			continue
		}
		version := "@" + p.Backend.Ref
		if g, ok := in.Lock.Plugs[p.ID]; ok && g.SHA != "" {
			version = "@" + g.SHA
		}
		full, red := PlugConfigs(cfg, p.Plug, in.PlugSecrets[p.ID])
		m.Plugs = append(m.Plugs, AdditionalPlug{
			Name: p.Backend.Name, PackageName: p.Backend.Package, Version: version, Configs: full,
		})
		redacted = append(redacted, AdditionalPlug{
			Name: p.Backend.Name, PackageName: p.Backend.Package, Version: version, Configs: red,
		})
	}
	plugsJSON, err := json.Marshal(nonNil(m.Plugs))
	if err != nil {
		return nil, fmt.Errorf("render: cannot encode ADDITIONAL_PLUGS: %w", err)
	}
	m.AdditionalPlugsJSON = string(plugsJSON)
	var red bytes.Buffer
	enc := json.NewEncoder(&red)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(nonNil(redacted)); err != nil {
		return nil, fmt.Errorf("render: cannot encode ADDITIONAL_PLUGS: %w", err)
	}
	m.AdditionalPlugsRedacted = strings.TrimSpace(red.String())

	allowed := append(append([]string{}, m.Sites...), "localhost", "127.0.0.1")
	origins := make([]string, 0, len(m.Sites))
	for _, s := range m.Sites {
		origins = append(origins, "https://"+s)
	}
	// ADDITIONAL_PLUGS can hold a secret from Phase 4, so it reaches the containers as the podman
	// secret care-additional-plugs (docs/solutions.md, section 1.4), not in backend.env.
	m.BackendFixed = []EnvVar{
		{"BUCKET_ENDPOINT", fmt.Sprintf("http://localhost:%d", PortS3)},
		{"BUCKET_EXTERNAL_ENDPOINT", "https://" + m.Canonical},
		{"BUCKET_PROVIDER", "MINIO"},
		{"CELERY_BROKER_URL", "redis://localhost:6379/0"},
		{"CSRF_TRUSTED_ORIGINS", mustJSON(origins)},
		{"DJANGO_ALLOWED_HOSTS", mustJSON(allowed)},
		{"POSTGRES_DB", m.DB.Name},
		{"POSTGRES_HOST", m.DB.Host},
		{"POSTGRES_PORT", m.DB.Port},
		{"POSTGRES_USER", m.DB.User},
		{"REDIS_URL", "redis://localhost:6379/0"},
	}
	m.BackendVars = sortedVars(pl.Backend)
	m.FrontendVars = sortedVars(pl.Frontend)

	m.WALTimeoutSec = cfg.Backups.WALArchiveTimeoutMin * 60
	m.PGRetentionFull = cfg.Backups.Retention.DBFull
	if !in.Bootstrap {
		m.Backup = newBackupModel(cfg)
	}

	if g, ok := in.Lock.Git["care_fe"]; ok && g.SHA != "" && !in.Bootstrap {
		m.FEBuildID = fe.BuildID(g.SHA, pl.Frontend)
		m.FESHA = g.SHA
		m.FERepo = GitHubSlug(g.Repo)
	}
	m.FEBuild = cfg.FE.Provider == "local" && !in.Bootstrap
	if m.FEBuild && m.FESHA != "" && m.FERepo == "" {
		return nil, fmt.Errorf("render: fe.provider local fetches care_fe from codeload.github.com, but the care_fe repository %s is not on github.com", in.Lock.Git["care_fe"].Repo)
	}
	if !in.Bootstrap {
		w := window.Window{Days: cfg.Updates.Window.Days, Start: cfg.Updates.Window.Start, End: cfg.Updates.Window.End}
		m.Timers = Timers{CheckCalendar: "*-*-* 12:00:00", CheckRandomDelay: "4h",
			ApplyCalendars: w.Calendars(), ApplyRandomDelay: window.Seconds(w.RandomDelay())}
		m.PlugBuild = cfg.Solution.Track == "custom" && cfg.FE.Provider == "local" && customFrontendRefs(cfg)
	}
	return m, nil
}

// FirewallOf returns the firewall part of the model for cfg. An empty policy is the default accept.
func FirewallOf(cfg *config.Config) FirewallModel {
	f := FirewallModel{Policy: cfg.Security.Firewall.Policy, SSH: cfg.Security.SSH.Allow}
	if f.Policy == "" {
		f.Policy = config.DefaultFirewallPolicy
	}
	return f
}

